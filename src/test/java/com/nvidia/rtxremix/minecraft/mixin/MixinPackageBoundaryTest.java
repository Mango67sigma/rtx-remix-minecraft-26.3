package com.nvidia.rtxremix.minecraft.mixin;

import com.google.gson.JsonArray;
import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import com.google.gson.JsonParser;
import com.nvidia.rtxremix.minecraft.RtxRemixMod;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.params.ParameterizedTest;
import org.junit.jupiter.params.provider.MethodSource;
import org.objectweb.asm.ClassReader;
import org.objectweb.asm.Opcodes;
import org.objectweb.asm.tree.AnnotationNode;
import org.objectweb.asm.tree.ClassNode;
import org.objectweb.asm.tree.FieldNode;
import org.objectweb.asm.tree.MethodNode;

import java.io.InputStreamReader;
import java.lang.annotation.Annotation;
import java.lang.reflect.AnnotatedElement;
import java.lang.reflect.Field;
import java.lang.reflect.Member;
import java.lang.reflect.Method;
import java.lang.reflect.Modifier;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.HashSet;
import java.util.List;
import java.util.Set;
import java.util.TreeSet;
import java.util.stream.Stream;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertNotNull;
import static org.junit.jupiter.api.Assertions.assertTrue;

class MixinPackageBoundaryTest {
    private static final String MIXIN_PACKAGE = "com.nvidia.rtxremix.minecraft.mixin";
    private static final String MIXIN_CONFIG = "rtx-remix-renderer.mixins.json";
    private static final String MOD_JSON = "fabric.mod.json";
    private static final String MIXIN_ANNOTATION_PACKAGE = "org.spongepowered.asm.mixin";
    private static final String MEMBER_PREFIX = "rtxremix$";

    @Test
    void productionMixinPackageContainsOnlyConfiguredMixins() throws Exception {
        Path mixinDirectory = classesRoot().resolve(MIXIN_PACKAGE.replace('.', '/'));

        Set<String> configured = configuredMixins(MIXIN_CONFIG);

        Set<String> unconfigured = new HashSet<>();
        try (Stream<Path> classes = Files.list(mixinDirectory)) {
            classes.map(path -> path.getFileName().toString())
                    .filter(name -> name.endsWith(".class") && !name.contains("$"))
                    .map(name -> name.substring(0, name.length() - ".class".length()))
                    .filter(name -> !configured.contains(name))
                    .forEach(unconfigured::add);
        }

        assertEquals(Set.of(), unconfigured,
                "ordinary runtime classes cannot live in Mixin's reserved package");
    }

    /**
     * Mixin merges every declared member that is not shadowed or generated by an
     * injector into the target class, where an unprefixed name can collide with the
     * target's own member or with another mod's mixin. The prefix is what keeps those
     * names distinct, so it is asserted rather than assumed.
     */
    @Test
    void mixinAddedMembersCarryTheModPrefix() throws Exception {
        Set<String> offenders = new TreeSet<>();
        for (String simpleName : configuredMixins(MIXIN_CONFIG)) {
            Class<?> mixin = Class.forName(
                    MIXIN_PACKAGE + "." + simpleName, false, getClass().getClassLoader());
            for (Member member : declaredMembers(mixin)) {
                if (isMerged(member) && !member.getName().toLowerCase().startsWith(MEMBER_PREFIX)) {
                    offenders.add(simpleName + "." + member.getName());
                }
            }
        }

        assertEquals(Set.of(), offenders,
                "mixin-added members must be prefixed with " + MEMBER_PREFIX);
    }

    /** A config fabric.mod.json does not register is never applied, so every one shipped must be. */
    @Test
    void everyShippedMixinConfigIsRegistered() throws Exception {
        Set<String> shipped = new TreeSet<>();
        try (Stream<Path> files = Files.list(resourcesRoot())) {
            files.map(path -> path.getFileName().toString())
                    .filter(name -> name.endsWith(".mixins.json"))
                    .forEach(shipped::add);
        }

        assertEquals(shipped, new TreeSet<>(registeredConfigs()),
                "fabric.mod.json registers exactly the mixin configs the mod ships");
    }

    /**
     * The mixins for another mod, Distant Horizons' or Entity Culling's, have a config, and a
     * package inside the reserved one, of their own. Their plugin is an ordinary class, so
     * it must live outside every mixin package.
     */
    @ParameterizedTest
    @MethodSource("optionalModConfigs")
    void optionalModMixinPackageContainsOnlyItsConfiguredMixins(String configName) throws Exception {
        JsonObject config = readConfig(configName);
        String mixinPackage = config.get("package").getAsString();
        assertTrue(mixinPackage.startsWith(MIXIN_PACKAGE + "."),
                configName + " keeps its mixins in a package inside the reserved one");
        String plugin = config.get("plugin").getAsString();
        assertFalse(plugin.startsWith(MIXIN_PACKAGE + "."), "the mixin plugin must not live in a mixin package");

        Set<String> configured = configuredMixins(configName);
        Set<String> present = new TreeSet<>();
        try (Stream<Path> classes = Files.list(classesRoot().resolve(mixinPackage.replace('.', '/')))) {
            classes.map(path -> path.getFileName().toString())
                    .filter(name -> name.endsWith(".class") && !name.contains("$"))
                    .map(name -> name.substring(0, name.length() - ".class".length()))
                    .forEach(present::add);
        }

        assertEquals(new TreeSet<>(configured), present,
                mixinPackage + " holds exactly the mixins " + configName + " configures");
    }

    /**
     * The prefix rule for the mixins for another mod. That mod is not on the test classpath,
     * so their class files are read rather than loaded.
     */
    @ParameterizedTest
    @MethodSource("optionalModConfigs")
    void optionalModMixinAddedMembersCarryTheModPrefix(String configName) throws Exception {
        Path directory = classesRoot().resolve(
                readConfig(configName).get("package").getAsString().replace('.', '/'));
        Set<String> offenders = new TreeSet<>();
        for (String simpleName : configuredMixins(configName)) {
            ClassNode mixin = new ClassNode();
            new ClassReader(Files.readAllBytes(directory.resolve(simpleName + ".class"))).accept(mixin, 0);
            assertTrue(mixin.interfaces.isEmpty(), simpleName + " implements an interface this check does not cover");
            for (FieldNode field : mixin.fields) {
                if (isMerged(field.access, field.visibleAnnotations, field.invisibleAnnotations)
                        && !field.name.toLowerCase().startsWith(MEMBER_PREFIX)) {
                    offenders.add(simpleName + "." + field.name);
                }
            }
            for (MethodNode method : mixin.methods) {
                if (method.name.startsWith("<")) continue;
                if (isMerged(method.access, method.visibleAnnotations, method.invisibleAnnotations)
                        && !method.name.toLowerCase().startsWith(MEMBER_PREFIX)) {
                    offenders.add(simpleName + "." + method.name);
                }
            }
        }

        assertEquals(Set.of(), offenders,
                "mixin-added members must be prefixed with " + MEMBER_PREFIX);
    }

    /** Every mixin config but the main one: those of the mods the renderer works alongside. */
    static List<String> optionalModConfigs() throws Exception {
        List<String> configs = registeredConfigs();
        configs.remove(MIXIN_CONFIG);
        return configs;
    }

    /** The mixin configs fabric.mod.json registers, in its order. */
    private static List<String> registeredConfigs() throws Exception {
        JsonObject mod;
        try (var reader = Files.newBufferedReader(resourcesRoot().resolve(MOD_JSON), StandardCharsets.UTF_8)) {
            mod = JsonParser.parseReader(reader).getAsJsonObject();
        }
        List<String> configs = new ArrayList<>();
        for (JsonElement entry : mod.getAsJsonArray("mixins")) {
            configs.add(entry.isJsonObject()
                    ? entry.getAsJsonObject().get("config").getAsString()
                    : entry.getAsString());
        }
        return configs;
    }

    private static Path classesRoot() throws Exception {
        return Path.of(RtxRemixMod.class.getProtectionDomain().getCodeSource().getLocation().toURI());
    }

    /**
     * The mod's own resource directory, found through its main mixin config: every mod jar on
     * the test classpath carries a fabric.mod.json of its own.
     */
    private static Path resourcesRoot() throws Exception {
        return Path.of(RtxRemixMod.class.getClassLoader().getResource(MIXIN_CONFIG).toURI()).getParent();
    }

    private static JsonObject readConfig(String name) throws Exception {
        try (var stream = RtxRemixMod.class.getClassLoader().getResourceAsStream(name)) {
            assertNotNull(stream, "missing " + name);
            return JsonParser.parseReader(
                    new InputStreamReader(stream, StandardCharsets.UTF_8)).getAsJsonObject();
        }
    }

    private static Set<String> configuredMixins(String configName) throws Exception {
        JsonObject config = readConfig(configName);
        Set<String> configured = new HashSet<>();
        addEntries(configured, config.getAsJsonArray("mixins"), configName);
        addEntries(configured, config.getAsJsonArray("client"), configName);
        addEntries(configured, config.getAsJsonArray("server"), configName);
        return configured;
    }

    /** The class-file form of {@link #isMerged(Member)}, for mixins whose targets cannot be loaded. */
    private static boolean isMerged(int access, List<AnnotationNode> visible, List<AnnotationNode> invisible) {
        if ((access & (Opcodes.ACC_SYNTHETIC | Opcodes.ACC_ABSTRACT)) != 0) return false;
        return !hasMixinAnnotation(visible) && !hasMixinAnnotation(invisible);
    }

    private static boolean hasMixinAnnotation(List<AnnotationNode> annotations) {
        if (annotations == null) return false;
        String prefix = "L" + MIXIN_ANNOTATION_PACKAGE.replace('.', '/') + "/";
        for (AnnotationNode annotation : annotations) {
            if (annotation.desc.startsWith(prefix)) return true;
        }
        return false;
    }

    private static List<Member> declaredMembers(Class<?> mixin) {
        List<Member> members = new ArrayList<>();
        for (Field field : mixin.getDeclaredFields()) members.add(field);
        for (Method method : mixin.getDeclaredMethods()) members.add(method);
        return members;
    }

    /** True when Mixin copies this member into the target under the name it has here. */
    private static boolean isMerged(Member member) {
        if (member.isSynthetic() || Modifier.isAbstract(member.getModifiers())) {
            return false;
        }
        for (Annotation annotation : ((AnnotatedElement) member).getAnnotations()) {
            if (annotation.annotationType().getName().startsWith(MIXIN_ANNOTATION_PACKAGE)) {
                return false;
            }
        }
        return !(member instanceof Method method) || !implementsInterfaceMethod(method);
    }

    /** An interface the mixin implements owns the name, and those interfaces are prefixed. */
    private static boolean implementsInterfaceMethod(Method method) {
        for (Class<?> implemented : method.getDeclaringClass().getInterfaces()) {
            try {
                implemented.getMethod(method.getName(), method.getParameterTypes());
                return true;
            } catch (NoSuchMethodException ignored) {
                // Declared by another interface, or by the mixin itself.
            }
        }
        return false;
    }

    private static void addEntries(Set<String> configured, JsonArray entries, String configName) {
        if (entries == null) return;
        for (JsonElement entry : entries) {
            String name = entry.getAsString();
            assertTrue(configured.add(name), name + " is listed twice in " + configName);
        }
    }
}
